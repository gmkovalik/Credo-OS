"""Generate the six Credo OS logos (overlay/usr/share/credo/logos/*.svg).

Every logo is a medallion drawn in one color ("currentColor", recolored per theme).
Only plain shapes, strokes and even-odd holes are used (no masks, clip paths or
filters), so Qt SVG (Plasma icons, Credo Center) and librsvg render them the same.

    python tools/make_logos.py
"""
import math
import pathlib
import re

OUT = pathlib.Path(__file__).resolve().parent.parent / "overlay/usr/share/credo/logos"
C = 256
SERIF = 'font-family="Noto Serif, DejaVu Serif, Liberation Serif, serif"'


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def pt(x, y):
    return f"{f(x)} {f(y)}"


def polar(r, deg, cx=C, cy=C):
    a = math.radians(deg - 90)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def frame():
    return (f'<circle cx="{C}" cy="{C}" r="236" fill="none" stroke="currentColor" stroke-width="14"/>\n'
            f'  <circle cx="{C}" cy="{C}" r="214" fill="none" stroke="currentColor" stroke-width="3.5"/>')


def svg(name, body):
    text = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">\n'
            f'  <!-- Credo OS logo: {name}. Generated by tools/make_logos.py -->\n'
            f'  {frame()}\n  <g fill="currentColor">\n{body}\n  </g>\n</svg>\n')
    (OUT / f"{name}.svg").write_text(text, encoding="utf-8")


def tapered(p1, p2, w_end, w_mid):
    """Stroke from p1 to p2 that is thicker in the middle (classical lettering)."""
    (x1, y1), (x2, y2) = p1, p2
    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
    L = math.hypot(x2 - x1, y2 - y1)
    nx, ny = -(y2 - y1) / L, (x2 - x1) / L
    e, m = w_end / 2, w_mid / 2
    pts = [(x1 + nx * e, y1 + ny * e), (mx + nx * m, my + ny * m), (x2 + nx * e, y2 + ny * e),
           (x2 - nx * e, y2 - ny * e), (mx - nx * m, my - ny * m), (x1 - nx * e, y1 - ny * e)]
    return "M" + " L".join(pt(*p) for p in pts) + " Z"


def serif_bar(p, direction, half_len, half_thick):
    """Small bar across the end of a stroke at p; direction is the stroke's unit vector."""
    ux, uy = direction
    nx, ny = -uy, ux
    x, y = p
    pts = [(x + nx * half_len + ux * half_thick, y + ny * half_len + uy * half_thick),
           (x - nx * half_len + ux * half_thick, y - ny * half_len + uy * half_thick),
           (x - nx * half_len - ux * half_thick, y - ny * half_len - uy * half_thick),
           (x + nx * half_len - ux * half_thick, y + ny * half_len - uy * half_thick)]
    return "M" + " L".join(pt(*q) for q in pts) + " Z"


def star(cx, cy, r_out, r_in, rot=0):
    pts = [polar(r_out if i % 2 == 0 else r_in, rot + i * 36, cx, cy) for i in range(10)]
    return "M" + " L".join(pt(*p) for p in pts) + " Z"


# ------------------------------------------------------------------ Chi-Rho (the user's artwork)
ART = pathlib.Path(__file__).resolve().parent / "assets/chirho-art.svg"


def chirho_art():
    """The Chi-Rho artwork (tools/assets/chirho-art.svg): its drawing as one-colour markup,
    with Inkscape's editor-only attributes removed. Returns (markup, width, height)."""
    s = ART.read_text(encoding="utf-8")
    vb = re.search(r'viewBox="([\d.\s-]+)"', s).group(1).split()
    w, h = float(vb[2]), float(vb[3])
    m = re.search(r'(<g[^>]*id="layer1"[^>]*>.*</g>)\s*</svg>', s, re.S)
    inner = m.group(1)
    inner = re.sub(r'\s(?:sodipodi|inkscape):[\w-]+="[^"]*"', "", inner)
    inner = re.sub(r'\sxlink:href="[^"]*"', "", inner)      # editor links; undeclared prefix = invalid XML
    inner = re.sub(r'\saria-label="[^"]*"', "", inner)
    inner = re.sub(r'\sstyle="[^"]*"', "", inner)          # fills come from the surrounding group
    return inner, w, h


def chirho():
    """The Chi-Rho medallion: the user's Chi-Rho inside the Credo ring; plus a plain glyph
    (no ring) used where the logo is small or must follow the text colour (the menu bar)."""
    inner, w, h = chirho_art()
    target_h = 318
    k = target_h / h
    x, y = C - w * k / 2, C - h * k / 2 + 4
    svg("chirho", f'    <g transform="translate({f(x)} {f(y)}) scale({k:.4f})">{inner}</g>')
    glyph = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{f(w * 6)}" '
             f'height="{f(h * 6)}">\n  <!-- Credo OS: Chi-Rho glyph (from tools/assets/chirho-art.svg) -->\n'
             f'  <g fill="currentColor">{inner}</g>\n</svg>\n')
    (OUT / "chirho-glyph.svg").write_text(glyph, encoding="utf-8")
    # Bold variant for the menu bar: the Chi-Rho alone (alpha and omega would shrink it to half
    # width at 22 px), with an outline in the same colour to thicken the fine serif strokes.
    # The viewBox is cropped to the letters (they span x 8.6-51 of the artwork).
    letters = re.sub(r'<g[^>]*id="text4733"[^>]*>.*?</g>', "", inner, flags=re.S)   # no nested groups inside
    letters = re.sub(r'<g[^>]*id="text34"[^>]*>.*?</g>', "", letters, flags=re.S)
    m = 2.2
    x0, x1 = 8.6 - m, 51.0 + m
    bold = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{f(x0)} {-m} {f(x1 - x0)} {f(h + 2 * m)}" '
            f'width="{f((x1 - x0) * 6)}" height="{f((h + 2 * m) * 6)}">\n'
            f'  <!-- Credo OS: bold Chi-Rho for the menu bar -->\n'
            f'  <g fill="currentColor" stroke="currentColor" stroke-width="{m * 1.2}" stroke-linejoin="round">'
            f'{letters}</g>\n</svg>\n')
    (OUT / "chirho-bold.svg").write_text(bold, encoding="utf-8")
    # Ready-coloured copies for the menu-bar button (white on dark bars, black on light bars)
    (OUT / "chirho-bold-white.svg").write_text(bold.replace("currentColor", "#ffffff"), encoding="utf-8")
    (OUT / "chirho-bold-black.svg").write_text(bold.replace("currentColor", "#141414"), encoding="utf-8")
    # Ringed Chi-Rho for the menu bar's Credo button, like the web app's logo but cleaner: one ring
    # (a double ring blurs at 22 px) and the Chi-Rho alone, without alpha and omega.
    k = 292 / h
    lx, ly = C - (8.6 + 51.0) / 2 * k, C - h * k / 2
    ring = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">\n'
            f'  <!-- Credo OS: Chi-Rho in a ring (menu bar) -->\n'
            f'  <circle cx="{C}" cy="{C}" r="232" fill="none" stroke="currentColor" stroke-width="30"/>\n'
            f'  <g transform="translate({f(lx)} {f(ly)}) scale({k:.4f})" fill="currentColor" stroke="currentColor" '
            f'stroke-width="1.5" stroke-linejoin="round">{letters}</g>\n</svg>\n')
    (OUT / "chirho-ring.svg").write_text(ring, encoding="utf-8")
    (OUT / "chirho-ring-white.svg").write_text(ring.replace("currentColor", "#ffffff"), encoding="utf-8")
    (OUT / "chirho-ring-black.svg").write_text(ring.replace("currentColor", "#141414"), encoding="utf-8")


def chirho_geometric():
    """The earlier geometric Chi-Rho (kept for reference; not generated)."""
    parts = []
    # Rho: stem with serifs, and the bowl.
    parts.append('<rect x="240" y="100" width="32" height="312"/>')
    parts.append('<rect x="206" y="404" width="100" height="16" rx="3"/>')
    parts.append('<rect x="226" y="90" width="46" height="14" rx="3"/>')
    parts.append('<path d="M256 104 H302 A70 70 0 0 1 302 244 H256" fill="none" stroke="currentColor" '
                 'stroke-width="28"/>')
    # Chi: two tapered strokes crossing the stem, with small serifs at the ends.
    a1, a2 = (150, 200), (362, 386)
    b1, b2 = (362, 200), (150, 386)
    for p, q in ((a1, a2), (b1, b2)):
        parts.append(f'<path d="{tapered(p, q, 20, 34)}"/>')
        L = math.hypot(q[0] - p[0], q[1] - p[1])
        u = ((q[0] - p[0]) / L, (q[1] - p[1]) / L)
        parts.append(f'<path d="{serif_bar(p, u, 17, 5)}"/>')
        parts.append(f'<path d="{serif_bar(q, u, 17, 5)}"/>')
    parts.append(f'<text x="112" y="318" {SERIF} font-size="74" text-anchor="middle">Α</text>')
    parts.append(f'<text x="400" y="318" {SERIF} font-size="74" text-anchor="middle">Ω</text>')
    svg("chirho", "    " + "\n    ".join(parts))


# ------------------------------------------------------------------ Latin cross (budded, on Calvary)
def cross():
    parts = ['<rect x="236" y="98" width="40" height="298"/>',
             '<rect x="132" y="170" width="248" height="40"/>']
    for (tx, ty), (s1, s2) in (((256, 80), ((232, 104), (280, 104))),
                               ((114, 190), ((136, 166), (136, 214))),
                               ((398, 190), ((376, 166), (376, 214)))):
        parts.append(f'<circle cx="{tx}" cy="{ty}" r="21"/>')
        parts.append(f'<circle cx="{s1[0]}" cy="{s1[1]}" r="16"/>')
        parts.append(f'<circle cx="{s2[0]}" cy="{s2[1]}" r="16"/>')
    # Three steps of Calvary (faith, hope, charity).
    parts += ['<rect x="212" y="394" width="88" height="16" rx="2"/>',
              '<rect x="192" y="414" width="128" height="16" rx="2"/>',
              '<rect x="172" y="434" width="168" height="16" rx="2"/>']
    # A quiet glory behind the crossing.
    for i in range(16):
        deg = i * 22.5 + 11.25
        p1, p2 = polar(70, deg, 256, 190), polar(108, deg, 256, 190)
        parts.append(f'<path d="M{pt(*p1)} L{pt(*p2)}" stroke="currentColor" stroke-width="5" '
                     f'stroke-linecap="round" fill="none"/>')
    svg("cross", "    " + "\n    ".join(parts))


# ------------------------------------------------------------------ IHS (sun of the Holy Name)
def ihs():
    parts = []
    for i in range(32):
        deg = i * 11.25
        long_ray = i % 2 == 0
        tip = polar(206 if long_ray else 184, deg)
        half = 7 if long_ray else 5
        b1, b2 = polar(152, deg - half * 0.42), polar(152, deg + half * 0.42)
        parts.append(f'<path d="M{pt(*b1)} L{pt(*tip)} L{pt(*b2)} Z"/>')
    parts.append(f'<circle cx="{C}" cy="{C}" r="140" fill="none" stroke="currentColor" stroke-width="8"/>')
    parts.append(f'<text x="256" y="308" {SERIF} font-size="116" font-weight="700" text-anchor="middle" '
                 f'letter-spacing="2">IHS</text>')
    # Cross rising from the crossbar of the H.
    parts.append('<rect x="250" y="150" width="12" height="78"/>')
    parts.append('<rect x="232" y="170" width="48" height="10"/>')
    # Three nails.
    for rot in (-24, 0, 24):
        parts.append(f'<g transform="rotate({rot} 256 384)"><path d="M256 386 L248.5 334 L263.5 334 Z"/>'
                     f'<rect x="243" y="326" width="26" height="8" rx="2"/></g>')
    svg("ihs", "    " + "\n    ".join(parts))


