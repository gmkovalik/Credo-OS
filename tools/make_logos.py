# ------------------------------------------------------------------ Marian monogram (Miraculous Medal)
def marian():
    parts = []
    for i in range(12):
        x, y = polar(190, i * 30 + 15)
        parts.append(f'<path d="{star(x, y, 15, 6.2, i * 30 + 15)}"/>')
    parts.append('<rect x="248" y="96" width="16" height="176"/>')
    parts.append('<rect x="214" y="136" width="84" height="14"/>')
    parts.append('<rect x="146" y="262" width="220" height="16" rx="3"/>')
    parts.append(f'<text x="256" y="420" {SERIF} font-size="230" font-weight="700" text-anchor="middle">M</text>')
    svg("marian", "    " + "\n    ".join(parts))


# ------------------------------------------------------------------ Sacred Heart
def bezier_q(p0, p1, p2, t):
    return tuple((1 - t) ** 2 * a + 2 * (1 - t) * t * b + t * t * c for a, b, c in zip(p0, p1, p2))


def sacredheart():
    heart = ("M256 434 C180 382 112 322 112 250 C112 200 148 166 192 166 C222 166 244 184 256 208 "
             "C268 184 290 166 320 166 C364 166 400 200 400 250 C400 322 332 382 256 434 Z")
    # Crown of thorns: a wavy band (hole) with thorn notches (holes) above and below it.
    top = [((126, 256), (191, 272), (256, 256)), ((256, 256), (321, 240), (386, 256))]
    bot = [((126, 276), (191, 292), (256, 276)), ((256, 276), (321, 260), (386, 276))]
    band = ("M126 256 Q191 272 256 256 Q321 240 386 256 L386 276 Q321 260 256 276 Q191 292 126 276 Z")
    thorns = []
    for seg, sign in ((top, -1), (bot, 1)):
        for p0, p1, p2 in seg:
            for t in (0.22, 0.5, 0.78):
                x, y = bezier_q(p0, p1, p2, t)
                y += sign * 2.5
                thorns.append(f"M{pt(x - 6, y)} L{pt(x + 6, y)} L{pt(x + 2, y + sign * 15)} Z")
    wound = "M282 318 Q300 328 318 350 Q296 342 282 318 Z"
    parts = [f'<path fill-rule="evenodd" d="{heart} {band} {" ".join(thorns)} {wound}"/>']
    # Flames and the cross above the heart.
    parts.append('<path d="M256 96 C278 128 298 150 290 180 C286 196 272 204 256 214 '
                 'C240 204 226 196 222 180 C214 150 234 128 256 96 Z"/>')
    parts.append('<path d="M220 170 C206 150 212 130 224 118 C224 140 236 152 234 176 Z"/>')
    parts.append('<path d="M292 170 C306 150 300 130 288 118 C288 140 276 152 278 176 Z"/>')
    parts.append('<rect x="250" y="44" width="12" height="62"/><rect x="234" y="60" width="44" height="10"/>')
    # Rays around the heart, leaving room for the flames.
    for i in range(24):
        deg = i * 15
        if deg <= 40 or deg >= 320:
            continue
        p1, p2 = polar(172, deg, 256, 286), polar(198, deg, 256, 286)
        parts.append(f'<path d="M{pt(*p1)} L{pt(*p2)}" stroke="currentColor" stroke-width="5" '
                     f'stroke-linecap="round" fill="none"/>')
    svg("sacredheart", "    " + "\n    ".join(parts))


