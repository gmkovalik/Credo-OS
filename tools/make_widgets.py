"""Write the shared glass-card component into each Credo desktop widget.

Plasma packages can't import QML from each other, so the card (glass look + drag-to-move,
using the desktop layout's own placeholder/snapping, + click) is copied into each widget
as contents/ui/GlassCard.qml.

    python tools/make_widgets.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLASMOIDS = ROOT / "overlay/usr/share/plasma/plasmoids"
WIDGETS = ["org.credo.today", "org.credo.rosary", "org.credo.clock"]

CARD = r"""// Glass card for Credo desktop widgets (generated by tools/make_widgets.py - edit there).
// Press and drag anywhere on the card to move the widget; a click without moving activates it.
// Moving uses the desktop's own layout (placeholder, snapping, saved position), like Plasma's
// edit-mode handle, but without entering edit mode first.
import QtQuick

Rectangle {
    id: card
    signal activated()
    property Item container: null
    property real cornerRadius: 24

    radius: cornerRadius
    color: Qt.rgba(1, 1, 1, 0.14)   // flat glass, no gradient
    border.color: Qt.rgba(1, 1, 1, 0.28)
    border.width: 1

    Rectangle {                              // top-edge highlight
        anchors { left: parent.left; right: parent.right; top: parent.top
                  leftMargin: card.cornerRadius; rightMargin: card.cornerRadius; topMargin: 1 }
        height: 1
        color: Qt.rgba(1, 1, 1, 0.45)
    }

    // The desktop wraps each widget in an ItemContainer (it has userDrag() and a layout).
    function findContainer() {
        var p = card.parent;
        while (p) {
            if (p.userDrag !== undefined && p.layout !== undefined) return p;
            p = p.parent;
        }
        return null;
    }
    Component.onCompleted: container = findContainer()

    MouseArea {
        id: mover
        anchors.fill: parent
        hoverEnabled: true
        property bool dragged: false
        cursorShape: drag.active ? Qt.ClosedHandCursor : Qt.PointingHandCursor
        drag.target: card.container
        drag.threshold: 6
        onPressed: {
            dragged = false;
            if (!card.container) card.container = card.findContainer();
        }
        onPositionChanged: function (mouse) {
            if (!pressed || !drag.active || !card.container) return;
            if (!dragged) {
                dragged = true;
                card.container.layout.releaseSpace(card.container);
            }
            card.container.layout.showPlaceHolderForItem(card.container);
            var p = mapToItem(card.container, mouse.x, mouse.y);
            card.container.userDrag(Qt.point(card.container.x, card.container.y), p);
        }
        onReleased: {
            if (dragged && card.container) {
                card.container.layout.hidePlaceHolder();
                card.container.layout.positionItem(card.container);
            }
        }
        onClicked: if (!dragged) card.activated()
    }
}
"""

if __name__ == "__main__":
    for w in WIDGETS:
        d = PLASMOIDS / w / "contents/ui"
        d.mkdir(parents=True, exist_ok=True)
        (d / "GlassCard.qml").write_text(CARD, encoding="utf-8")
        print("wrote", d / "GlassCard.qml")
